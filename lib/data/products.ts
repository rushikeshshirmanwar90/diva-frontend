/** Ring sizes are Indian sizing; stock varies so the PDP can show sold-out states. */
function ringSizes(
  sku: string,
  weight: number,
  stocks: number[] = [4, 7, 9, 6, 3, 0, 2],
): Variant[] {
  return [10, 11, 12, 13, 14, 15, 16].map((size, i) => ({
    id: `${sku}-${size}`,
    label: String(size),
    sku: `${sku}-R${size}`,
    stock: stocks[i] ?? 3,
    priceDelta: rupees((size - 12) * 320),
    weightGrams: +(weight + (size - 12) * 0.12).toFixed(2),
  }));
}

function chainLengths(sku: string, weight: number): Variant[] {
  return [
    { len: 16, delta: 0, stock: 8 },
    { len: 18, delta: 4200, stock: 11 },
    { len: 20, delta: 8600, stock: 4 },
  ].map(({ len, delta, stock }) => ({
    id: `${sku}-${len}`,
    label: `${len} in`,
    sku: `${sku}-L${len}`,
    stock,
    priceDelta: rupees(delta),
    weightGrams: +(weight + (len - 16) * 0.45).toFixed(2),
  }));
}

function oneSize(sku: string, weight: number, stock = 12): Variant[] {
  return [
    {
      id: `${sku}-os`,
      label: "One size",
      sku: `${sku}-OS`,
      stock,
      priceDelta: 0,
      weightGrams: weight,
    },
  ];
}

