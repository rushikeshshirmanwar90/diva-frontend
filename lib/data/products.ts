/* ───────────────────────────── Lookups ──────────────────────────────── */

export function getProduct(slug: string) {
  return products.find((p) => p.slug === slug);
}

export function productsByCategory(slug: string) {
  return products.filter((p) => p.categorySlug === slug);
}

export function productsByCollection(slug: string) {
  return products.filter((p) => p.collectionSlugs.includes(slug));
}

export function productsByBadge(badge: "new" | "bestseller" | "limited") {
  return products.filter((p) => p.badges.includes(badge));
}

/** Same category first, then anything sharing a collection. */
export function relatedProducts(product: Product, limit = 4) {
  const sameCategory = products.filter(
    (p) => p.categorySlug === product.categorySlug && p.slug !== product.slug,
  );
  const sharedCollection = products.filter(
    (p) =>
      p.slug !== product.slug &&
      p.categorySlug !== product.categorySlug &&
      p.collectionSlugs.some((c) => product.collectionSlugs.includes(c)),
  );
  return [...sameCategory, ...sharedCollection].slice(0, limit);
}

export function searchProducts(query: string) {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return products.filter((p) =>
    [
      p.title,
      p.subtitle,
      p.categorySlug,
      p.attributes.metal,
      p.attributes.stone,
      ...p.attributes.occasions,
    ]
      .join(" ")
      .toLowerCase()
      .includes(q),
  );
}

/** Cheapest in-stock variant price, used for card display. */
export function fromPrice(product: Product) {
  const deltas = product.variants.map((v) => v.priceDelta);
  return product.price + Math.min(...deltas);
}
